void solve()
{
    i64 a, b;
    cin >> a >> b;
    if (a < b) swap(a, b);
    i64 ans = 0;
    if (a == b)
        ans = 0;
    else if (a % b == 0)
        ans = 1;
    else
        ans = 2;
    cout << ans << endl;
}
